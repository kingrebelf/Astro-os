#!/usr/bin/env python3
"""Turn a stock Openbox rc.xml into the ASTRO//OS one.   rcxml.py SRC DEST MARK [--keys]

--keys also adds the ASTRO//OS keyboard shortcuts (used by the standalone distro).
"""
import re
import sys

KEYS = """
    <keybind key="C-A-t"><action name="Execute"><command>/opt/astro-os/astroctl launch term</command></action></keybind>
    <keybind key="W-e"><action name="Execute"><command>/opt/astro-os/astroctl launch files</command></action></keybind>
    <keybind key="W-b"><action name="Execute"><command>/opt/astro-os/astroctl launch web</command></action></keybind>
    <keybind key="W-c"><action name="Execute"><command>/opt/astro-os/astroctl launch opencode</command></action></keybind>
    <keybind key="C-S-Escape"><action name="Execute"><command>/opt/astro-os/astroctl launch tasks</command></action></keybind>
"""

src, dest, mark = sys.argv[1:4]
s = open(src).read()
s = re.sub(r"(<theme>.*?<name>)[^<]*(</name>)", r"\1AstroOS\2", s, count=1, flags=re.S)
s = re.sub(r"<name>(Ubuntu|sans)[^<]*</name>", "<name>Ubuntu Mono</name>", s)
# title-bar drags become outline drags (mover.py): moving whole windows floods the slow video chip
s = re.sub(r'(<context name="Titlebar">\s*<mousebind button="Left" action="Drag">\s*)<action name="Move"/>',
           "\\1<action name=\"Execute\"><command>sh -c 'kill -USR1 $(cat $XDG_RUNTIME_DIR/astro-os/mover.pid)'</command></action>", s, count=1)
s = re.sub(r"<drawContents>\s*yes\s*</drawContents>", "<drawContents>no</drawContents>", s)
if "--keys" in sys.argv:
    s = s.replace("</keyboard>", KEYS + "  </keyboard>", 1)
s = s.replace("?>", f"?>\n<!-- {mark}: generated by ASTRO//OS, removed when you exit it -->", 1)
open(dest, "w").write(s)
